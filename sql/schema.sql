-- ============================================================================
-- DIMENSION TABLES
-- ============================================================================

CREATE TABLE IF NOT EXISTS "Dim_Time" (
    time_id INTEGER PRIMARY KEY,
    date_full DATE NOT NULL UNIQUE,
    year INTEGER NOT NULL,
    month INTEGER NOT NULL,
    day INTEGER NOT NULL,
    week_of_year INTEGER NOT NULL,
    quarter INTEGER NOT NULL,
    day_of_week VARCHAR(10) NOT NULL,
    is_weekend BOOLEAN NOT NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE INDEX IF NOT EXISTS idx_dim_time_date
    ON "Dim_Time" (date_full);
CREATE INDEX IF NOT EXISTS idx_dim_time_year_month
    ON "Dim_Time" (year, month);


CREATE TABLE IF NOT EXISTS "Dim_Location" (
    location_id INTEGER PRIMARY KEY,
    site_code VARCHAR(50) NOT NULL UNIQUE,
    site_name VARCHAR(255) NOT NULL,
    region VARCHAR(100),
    country VARCHAR(100) NOT NULL DEFAULT 'South Africa',
    latitude NUMERIC(10, 8),
    longitude NUMERIC(11, 8),
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE INDEX IF NOT EXISTS idx_dim_location_site_code
    ON "Dim_Location" (site_code);
CREATE INDEX IF NOT EXISTS idx_dim_location_site_name
    ON "Dim_Location" (site_name);


CREATE TABLE IF NOT EXISTS "Dim_Patient" (
    patient_id INTEGER PRIMARY KEY,
    patient_code VARCHAR(50) NOT NULL UNIQUE,
    age_group VARCHAR(20) NOT NULL,
    sex VARCHAR(10) NOT NULL,
    bmi_category VARCHAR(50),
    smoking_status VARCHAR(50),
    household_id VARCHAR(50),
    role_in_network VARCHAR(50) NOT NULL DEFAULT 'Contact',
    sars_status VARCHAR(20) NOT NULL DEFAULT 'Unknown',
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE INDEX IF NOT EXISTS idx_dim_patient_patient_code
    ON "Dim_Patient" (patient_code);
CREATE INDEX IF NOT EXISTS idx_dim_patient_age_group
    ON "Dim_Patient" (age_group);
CREATE INDEX IF NOT EXISTS idx_dim_patient_sex
    ON "Dim_Patient" (sex);
CREATE INDEX IF NOT EXISTS idx_dim_patient_household
    ON "Dim_Patient" (household_id);


-- ============================================================================
-- FACT TABLE
-- ============================================================================

CREATE TABLE IF NOT EXISTS "Fact_Exposure" (
    exposure_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    time_id INTEGER NOT NULL,
    location_id INTEGER NOT NULL,
    patient_id INTEGER NOT NULL,
    contact_patient_id INTEGER,
    count_exposure INTEGER NOT NULL DEFAULT 1,
    exposure_strength NUMERIC(10, 4),
    sars_status_patient VARCHAR(20),
    susceptibility_status VARCHAR(50),
    variant_type VARCHAR(100),
    contact_duration_category VARCHAR(50),
    is_threshold_exceeded BOOLEAN NOT NULL DEFAULT TRUE,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,

    CONSTRAINT fk_exposure_time
        FOREIGN KEY (time_id) REFERENCES "Dim_Time" (time_id),
    CONSTRAINT fk_exposure_location
        FOREIGN KEY (location_id) REFERENCES "Dim_Location" (location_id),
    CONSTRAINT fk_exposure_patient
        FOREIGN KEY (patient_id) REFERENCES "Dim_Patient" (patient_id),
    CONSTRAINT fk_exposure_contact
        FOREIGN KEY (contact_patient_id) REFERENCES "Dim_Patient" (patient_id),
    CONSTRAINT chk_fact_exposure_count_positive
        CHECK (count_exposure > 0)
);

CREATE INDEX IF NOT EXISTS idx_fact_exposure_time
    ON "Fact_Exposure" (time_id);
CREATE INDEX IF NOT EXISTS idx_fact_exposure_location
    ON "Fact_Exposure" (location_id);
CREATE INDEX IF NOT EXISTS idx_fact_exposure_patient
    ON "Fact_Exposure" (patient_id);
CREATE INDEX IF NOT EXISTS idx_fact_exposure_contact
    ON "Fact_Exposure" (contact_patient_id);
CREATE INDEX IF NOT EXISTS idx_fact_exposure_composite
    ON "Fact_Exposure" (time_id, location_id, patient_id);
CREATE INDEX IF NOT EXISTS idx_fact_exposure_threshold
    ON "Fact_Exposure" (is_threshold_exceeded);


-- ============================================================================
-- ANALYSIS VIEWS
-- ============================================================================

CREATE OR REPLACE VIEW v_exposure_summary AS
SELECT
    fe.exposure_id,
    dt.date_full,
    dt.year,
    dt.month,
    dl.site_name,
    dl.region,
    dp.patient_code,
    dp.age_group,
    dp.sex,
    fe.count_exposure,
    fe.sars_status_patient,
    fe.susceptibility_status,
    fe.variant_type,
    fe.is_threshold_exceeded,
    fe.created_at
FROM "Fact_Exposure" fe
JOIN "Dim_Time" dt ON fe.time_id = dt.time_id
JOIN "Dim_Location" dl ON fe.location_id = dl.location_id
JOIN "Dim_Patient" dp ON fe.patient_id = dp.patient_id
WHERE fe.is_threshold_exceeded = TRUE;


CREATE OR REPLACE VIEW v_exposure_network AS
SELECT
    fe.exposure_id,
    dt.date_full,
    dl.site_name,
    dp_primary.patient_code AS primary_patient_code,
    dp_primary.age_group AS primary_age_group,
    dp_contact.patient_code AS contact_patient_code,
    dp_contact.age_group AS contact_age_group,
    fe.count_exposure,
    fe.sars_status_patient,
    fe.variant_type
FROM "Fact_Exposure" fe
JOIN "Dim_Time" dt ON fe.time_id = dt.time_id
JOIN "Dim_Location" dl ON fe.location_id = dl.location_id
JOIN "Dim_Patient" dp_primary ON fe.patient_id = dp_primary.patient_id
LEFT JOIN "Dim_Patient" dp_contact ON fe.contact_patient_id = dp_contact.patient_id
WHERE fe.is_threshold_exceeded = TRUE
  AND fe.contact_patient_id IS NOT NULL;


CREATE OR REPLACE VIEW v_exposure_by_location_time AS
SELECT
    dt.year,
    dt.month,
    dt.date_full,
    dl.site_name,
    dl.region,
    COUNT(fe.exposure_id) AS total_exposures,
    SUM(fe.count_exposure) AS total_exposure_count,
    COUNT(DISTINCT fe.patient_id) AS unique_patients,
    COUNT(DISTINCT fe.contact_patient_id) AS unique_contacts,
    AVG(fe.exposure_strength) AS avg_exposure_strength
FROM "Fact_Exposure" fe
JOIN "Dim_Time" dt ON fe.time_id = dt.time_id
JOIN "Dim_Location" dl ON fe.location_id = dl.location_id
WHERE fe.is_threshold_exceeded = TRUE
GROUP BY dt.year, dt.month, dt.date_full, dl.site_name, dl.region;
